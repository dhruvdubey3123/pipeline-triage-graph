"""The twelve procedures, as SQL.

Source data is TPC-H, generated by DuckDB. The source tables are not nodes: a node is something a
person wrote and can break. Each node is a procedure that rebuilds one table of the same name, and
declares what an on-call engineer would write down about it: who owns it, what one row means, what
it reads from, and what should stay true from one run to the next.

    staging        stg_orders  stg_lineitem  stg_customer  stg_supplier
    intermediate   int_order_items  int_customer_geo  int_part_cost
    marts          mart_daily_revenue  mart_customer_revenue  mart_supplier_performance
    reports        rpt_revenue_dashboard  rpt_regional_summary

Both reports reach int_order_items by more than one path, and four nodes read from more than one
parent, so a tracer that only handles a straight chain does not get through this.
"""
from __future__ import annotations

from dataclasses import dataclass

from ..dag import PipelineDAG


@dataclass(frozen=True)
class NodeDef:
    id: str
    layer: str
    owner: str
    grain: tuple[str, ...]              # the columns that identify one row
    parents: tuple[str, ...]            # other nodes it reads from (declared lineage)
    sql: str
    same_rows_as: str | None = None     # a parent it must have exactly as many rows as
    date_col: str | None = None         # a column whose latest value says how current the table is


NODES: tuple[NodeDef, ...] = (
    NodeDef("stg_orders", "staging", "data-eng", ("order_id",), (),
            "select o_orderkey as order_id, o_custkey as customer_id, o_orderdate as order_date, "
            "o_orderstatus as status from raw.orders"),
    NodeDef("stg_lineitem", "staging", "data-eng", ("order_id", "line_no"), (),
            "select l_orderkey as order_id, l_linenumber as line_no, l_partkey as part_id, l_suppkey as supplier_id, "
            "l_quantity as quantity, l_extendedprice as extended_price, l_discount as discount from raw.lineitem"),
    NodeDef("stg_customer", "staging", "data-eng", ("customer_id",), (),
            "select c_custkey as customer_id, c_nationkey as nation_id, c_mktsegment as segment from raw.customer"),
    NodeDef("stg_supplier", "staging", "data-eng", ("supplier_id",), (),
            "select s_suppkey as supplier_id, s_name as supplier_name, s_nationkey as nation_id from raw.supplier"),
    NodeDef("int_order_items", "intermediate", "analytics-eng", ("order_id", "line_no"), ("stg_lineitem", "stg_orders"),
            "select l.order_id, l.line_no, o.customer_id, o.order_date, l.part_id, l.supplier_id, l.quantity, "
            "l.extended_price * (1 - l.discount) as net_revenue "
            "from stg_lineitem l join stg_orders o on o.order_id = l.order_id",
            same_rows_as="stg_lineitem"),
    NodeDef("int_customer_geo", "intermediate", "analytics-eng", ("customer_id",), ("stg_customer",),
            "select c.customer_id, c.segment, coalesce(n.n_name, 'UNASSIGNED') as nation, "
            "coalesce(r.r_name, 'UNASSIGNED') as region "
            "from stg_customer c left join raw.nation n on n.n_nationkey = c.nation_id "
            "left join raw.region r on r.r_regionkey = n.n_regionkey",
            same_rows_as="stg_customer"),
    NodeDef("int_part_cost", "intermediate", "analytics-eng", ("order_id", "line_no"), ("stg_lineitem",),
            "select l.order_id, l.line_no, l.quantity * ps.ps_supplycost as supply_cost "
            "from stg_lineitem l left join raw.partsupp ps on ps.ps_partkey = l.part_id and ps.ps_suppkey = l.supplier_id",
            same_rows_as="stg_lineitem"),
    NodeDef("mart_daily_revenue", "mart", "analytics-eng", ("order_date",), ("int_order_items",),
            "select order_date, count(distinct order_id) as orders, sum(net_revenue) as revenue from int_order_items "
            "where order_date > (select as_of from meta) - 90 and order_date <= (select as_of from meta) "
            "group by order_date",
            date_col="order_date"),
    NodeDef("mart_customer_revenue", "mart", "analytics-eng", ("customer_id",), ("int_customer_geo", "int_order_items"),
            "select g.customer_id, g.region, g.segment, coalesce(sum(i.net_revenue), 0) as revenue, "
            "count(distinct i.order_id) as orders "
            "from int_customer_geo g left join int_order_items i on i.customer_id = g.customer_id "
            "group by g.customer_id, g.region, g.segment",
            same_rows_as="int_customer_geo"),
    NodeDef("mart_supplier_performance", "mart", "analytics-eng", ("supplier_id",),
            ("stg_supplier", "int_order_items", "int_part_cost"),
            "select s.supplier_id, s.supplier_name, sum(i.net_revenue) as revenue, "
            "sum(coalesce(c.supply_cost, 0)) as cost, sum(i.net_revenue - coalesce(c.supply_cost, 0)) as margin "
            "from stg_supplier s join int_order_items i on i.supplier_id = s.supplier_id "
            "left join int_part_cost c on c.order_id = i.order_id and c.line_no = i.line_no "
            "group by s.supplier_id, s.supplier_name"),
    NodeDef("rpt_revenue_dashboard", "report", "bi", ("region", "segment"),
            ("mart_daily_revenue", "mart_customer_revenue"),
            "select m.region, m.segment, sum(m.revenue) as revenue, sum(m.orders) as orders, "
            "(select max(order_date) from mart_daily_revenue) as latest_day, "
            "(select sum(revenue) from mart_daily_revenue "
            "where order_date > (select max(order_date) from mart_daily_revenue) - 7) as trailing_7d_revenue "
            "from mart_customer_revenue m group by m.region, m.segment",
            date_col="latest_day"),
    NodeDef("rpt_regional_summary", "report", "bi", ("region",),
            ("mart_customer_revenue", "mart_supplier_performance"),
            "select m.region, count(*) as customers, sum(m.revenue) as revenue, "
            "sum(m.revenue) / (select sum(revenue) from mart_customer_revenue) as revenue_share, "
            "(select sum(margin) / sum(revenue) from mart_supplier_performance) as margin_rate "
            "from mart_customer_revenue m group by m.region"),
)

BY_ID = {n.id: n for n in NODES}
REPORTS = tuple(n.id for n in NODES if n.layer == "report")


def as_dag() -> PipelineDAG:
    """The same pipeline in the form the tracer walks. Reports are reports; everything else is a procedure."""
    return PipelineDAG.from_dict({
        "name": "tpch-revenue",
        "nodes": [{"id": n.id, "kind": "report" if n.layer == "report" else "procedure", "owner": n.owner} for n in NODES],
        "edges": [[p, n.id] for n in NODES for p in n.parents],
    })
